class FilesManager:
    """
    Отвечает за работу со всеми ассетами игры.
    """
    def __init__(self, paths: Optional[dict]=None):

        if paths is None:
            paths = {"images": "./game/images", "music": "./game/music", "sounds": "./game/sounds"}

        def find_files(extensions: list[str],
                       start_path: Union[str, Path],
                       exclude: Optional[list[str]] = None) -> dict:

            if exclude is None:
                exclude = []

            extensions_lower = [ext.lower() for ext in extensions]
            results = {}

            start_path = Path(start_path).resolve()
            if not start_path.exists():
                return results

            for root, dirs, files in os.walk(str(start_path)):
                root_parts = Path(root).parts
                if any(part in exclude for part in root_parts):
                    continue

                for file in files:
                    if any(file.lower().endswith(ext) for ext in extensions_lower):
                        file_path = Path(root) / file
                        results[str(file_path.name)] = file_path.absolute()

            return results


        self.images_path = Path(paths["images"]).absolute()
        self.music_path = Path(paths["music"]).absolute()
        self.sounds_path = Path(paths["sounds"]).absolute()

        self.image_extensions = [".png", ".jpg", ".jpeg", ".PNG", ".JPEG", ".gif", ".GIF"]
        self.audio_extensions = [".mp3", ".wav", ".ogg"]

        self.textures_paths: dict[str : Path] = find_files(self.image_extensions, self.images_path) # Пути к текстурам всех спрайтов {Название файла : полный путь}
        self.audio_paths: dict[str : Path] = (find_files(self.audio_extensions, self.music_path, ["voice"]) |
                                              find_files(self.audio_extensions, self.sounds_path, ["voice"])) # Пути ко всем звуковым файлам {Название файла : полный путь}
        self.loaded_labels: list[str] = [] # Лейблы которые уже были загружены

        self.textures: dict[str : Texture] = {} # Уже загруженные текстуры {Название файла : текстура}
        self.audios: dict[str : Sound] = {} # Уже загруженные звуки {Название файла : Звук}

    def load_assets(self, filenames: list[str], label: str) -> Optional[Thread]:
        """
        Загружает текстуры пачками в другом потоке
        :param filenames: список названий файлов
        :param label: Ассеты какого лейбла сейчас грузятся
        """

        if label in self.loaded_labels:
            return None # Если текстура уже загружена, то скипаем

        self.loaded_labels.append(label)

        textures_paths = self.textures_paths
        audio_paths = self.audio_paths
        textures = self.textures
        audios = self.audios

        def load(filenames):

            for i in filenames:
                if i in textures_paths and i not in textures:
                    path = str(textures_paths[i])
                    if path.endswith(".gif"):
                        textures[i] = load_animated_gif(path)
                    else:
                        #textures[i] = load_texture(path)

                        #'''
                        im: Image.Image = Image.open(path)  # type: ignore
                        
                        original_size = tuple(im.size)
                        size_resiz = (int(im.size[0] * 0.7), int(im.size[1] * 0.7))
                        im = im.resize(size_resiz, Image.Resampling.LANCZOS, reducing_gap=5.0)

                        if im.mode != "RGBA":
                            im = im.convert("RGBA")

                        im = im.resize(original_size, Image.Resampling.LANCZOS, reducing_gap=5.0)

                        tex = Texture(im, hit_box_algorithm=None)

                        tex.file_path = Path(path)

                        textures[i] = tex
                        #'''

                elif i in audio_paths and i not in audios:
                    path = str(audio_paths[i])
                    try:
                        duration = mutagen.File(path).info.length
                        streaming = duration > 10
                    except:
                        streaming = False

                    audios[i] = load_sound(path, streaming=streaming)

            default_texture_cache.flush(True, True, True, True)

        target = Thread(target=load, args=(filenames,))
        target.start()
        return target

    def get_character_textures(self, sprite: str) ->  dict[str : Texture]:
        """
        Возвращает текстуру персонажа
        :param sprite: Название спрайта
        """
        textures = {}
        for i in self.textures:
            if str(i).startswith(sprite):
                textures[".".join(i.split(".")[:-1])] = self.textures[i]
        return textures

